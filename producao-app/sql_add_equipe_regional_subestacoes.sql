-- Adiciona "Equipe Regional" ao cadastro de subestações — campo fixo (dropdown),
-- valores definidos pelo usuário a partir do "EQUIPE" da planilha original.
-- Diferente de superintendencia: no histórico, 21 das 369 subestações têm mais
-- de 1 valor distinto de EQUIPE entre visitas (a equipe despachada mudou ao
-- longo do tempo) — mesmo assim, aqui é 1 valor fixo por subestação (decisão
-- do usuário, "campo na hora do cadastro"), resolvido pela moda (valor mais
-- frequente), igual ao que já foi feito para porte/tipo na importação original.

ALTER TABLE d_subestacoes ADD COLUMN IF NOT EXISTS equipe_regional text
  CHECK (equipe_regional IN ('AT - SUD 04', 'CENTRO', 'NORDESTE', 'NORTE', 'SUL'));

COMMENT ON COLUMN d_subestacoes.equipe_regional IS
  'Equipe regional responsável (campo "EQUIPE" da planilha original) — fixo por subestação, escolhido no cadastro.';

