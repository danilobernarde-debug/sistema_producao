-- ============================================================
-- Reconstrói cada visita a partir dos lançamentos já no banco
-- (par Em Andamento + conclusão, ou registro único) e casa contra
-- a tabela acima pra preencher metadata_registro.equipe_regional
-- em ambos os lançamentos da visita.
-- ============================================================
DO $$
DECLARE
  r                RECORD;
  v_pendente_id    bigint;
  v_pendente_data  date;
  v_sub_atual      bigint;
  v_equipe         text;
  v_atualizados    integer := 0;
  v_sem_match      integer := 0;
BEGIN
  v_sub_atual := NULL;

  FOR r IN
    SELECT
      f.id AS registro_id,
      f.data_producao,
      (f.metadata_registro->>'subestacao_id')::bigint AS subestacao_id,
      regexp_replace(s.nome, '^\[[A-Za-z]+\]\s*', '') AS nome_sub,
      f.metadata_registro->>'os' AS os,
      EXISTS (
        SELECT 1 FROM f_prod_atividades a
        JOIN d_atividades da ON da.id = a.atividade_id
        WHERE a.registro_id = f.id AND da.codigo_op = 'LSE-AND'
      ) AS tem_andamento,
      EXISTS (
        SELECT 1 FROM f_prod_atividades a
        JOIN d_atividades da ON da.id = a.atividade_id
        WHERE a.registro_id = f.id AND da.codigo_op IN ('LSE-P','LSE-M','LSE-G','LSE-GG','LSE-XG','CQ-CHAV','CQ-MT','CQ-AT')
      ) AS tem_conclusao
    FROM f_prod_registro f
    JOIN d_subestacoes s ON s.id = (f.metadata_registro->>'subestacao_id')::bigint
    WHERE f.metadata_registro ? 'origem_backfill_linha'
      AND NOT (f.metadata_registro ? 'equipe_regional')
    ORDER BY (f.metadata_registro->>'subestacao_id')::bigint, f.data_producao, f.id
  LOOP
    IF v_sub_atual IS DISTINCT FROM r.subestacao_id THEN
      v_pendente_id   := NULL;
      v_pendente_data := NULL;
      v_sub_atual     := r.subestacao_id;
    END IF;

    IF r.tem_conclusao THEN
      SELECT equipe_regional INTO v_equipe FROM stg_equipe_visita
      WHERE nome = r.nome_sub AND os = r.os
        AND data_inicial = COALESCE(v_pendente_data, r.data_producao)
        AND data_final   = r.data_producao;

      IF v_equipe IS NOT NULL THEN
        IF v_pendente_id IS NOT NULL THEN
          UPDATE f_prod_registro
          SET metadata_registro = metadata_registro || jsonb_build_object('equipe_regional', v_equipe)
          WHERE id = v_pendente_id;
          v_atualizados := v_atualizados + 1;
        END IF;

        UPDATE f_prod_registro
        SET metadata_registro = metadata_registro || jsonb_build_object('equipe_regional', v_equipe)
        WHERE id = r.registro_id;
        v_atualizados := v_atualizados + 1;
      ELSE
        v_sem_match := v_sem_match + 1;
        RAISE WARNING 'Sem correspondência: subestação=% os=% inicio=% fim=% (registro_id=%)',
          r.nome_sub, r.os, COALESCE(v_pendente_data, r.data_producao), r.data_producao, r.registro_id;
      END IF;

      v_pendente_id   := NULL;
      v_pendente_data := NULL;
    ELSIF r.tem_andamento THEN
      v_pendente_id   := r.registro_id;
      v_pendente_data := r.data_producao;
    END IF;
  END LOOP;

  RAISE NOTICE 'OK — % lançamentos atualizados, % visitas sem correspondência na planilha.', v_atualizados, v_sem_match;
END $$;

DROP TABLE stg_equipe_visita;

