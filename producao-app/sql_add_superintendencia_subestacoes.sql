-- Adiciona a Superintendência (campo "SUPERINTENDÊNCIA" da planilha original) ao
-- cadastro de subestações. É um atributo puramente informativo/organizacional
-- (não influencia preço, ao contrário de porte/tipo), por isso texto livre,
-- igual município — sem reaproveitar d_regional (tabela genérica, compartilhada
-- com outros contratos, com sua própria semântica de regional).

