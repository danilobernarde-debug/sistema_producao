-- ============================================================
-- Aplica o staging nas tabelas reais
-- ============================================================
DO $$
DECLARE
  v_tipo_equipe_id  bigint;
  r                 RECORD;
  v_registro_id     bigint;
  v_subestacao_id   bigint;
  v_equipe_id       bigint;
  v_encarregado_id  bigint;
  v_campo_sub_id    bigint;
  v_campo_os_id     bigint;
  v_atividade_id    integer;
  v_ativ            RECORD;
  v_total_reg       integer := 0;
  v_total_ativ      integer := 0;
  v_pulados         integer := 0;
BEGIN
  SELECT id INTO v_tipo_equipe_id FROM d_tipo_equipe WHERE descricao = 'Limpeza de Subestação';
  IF v_tipo_equipe_id IS NULL THEN
    RAISE EXCEPTION 'Tipo de equipe "Limpeza de Subestação" não encontrado — rode sql_limpeza_subestacao.sql primeiro.';
  END IF;

  SELECT id INTO v_campo_sub_id FROM config_campos WHERE nome = 'subestacao_id';
  SELECT id INTO v_campo_os_id  FROM config_campos WHERE nome = 'os';
  IF v_campo_sub_id IS NULL OR v_campo_os_id IS NULL THEN
    RAISE EXCEPTION 'Campo subestacao_id ou os não encontrado em config_campos.';
  END IF;

  FOR r IN SELECT * FROM stg_registros ORDER BY linha_id LOOP
    -- já rodou antes pra essa linha? (idempotência)
    IF EXISTS (
      SELECT 1 FROM f_prod_registro
      WHERE contrato_id = 21
        AND (metadata_registro->>'origem_backfill_linha')::int = r.linha_id
    ) THEN
      v_pulados := v_pulados + 1;
      CONTINUE;
    END IF;

    SELECT id INTO v_subestacao_id FROM d_subestacoes WHERE nome = r.subestacao_nome AND contrato_id = 21;
    IF v_subestacao_id IS NULL THEN
      RAISE WARNING 'Subestação não encontrada: % (linha %) — pulando', r.subestacao_nome, r.linha_id;
      CONTINUE;
    END IF;

    SELECT id INTO v_equipe_id FROM d_equipes WHERE equipe = r.equipe_nome AND tipo_equipe_id = v_tipo_equipe_id;
    IF v_equipe_id IS NULL THEN
      RAISE WARNING 'Equipe não encontrada: % (linha %) — pulando', r.equipe_nome, r.linha_id;
      CONTINUE;
    END IF;

    SELECT id INTO v_encarregado_id FROM d_colaboradores WHERE equipe_id = v_equipe_id LIMIT 1;

    INSERT INTO f_prod_registro (
      data_producao, contrato_id, tipo_equipe_id, equipe_id, encarregado_id, metadata_registro
    ) VALUES (
      r.data_producao, 21, v_tipo_equipe_id, v_equipe_id, v_encarregado_id,
      jsonb_build_object(
        'subestacao_id', v_subestacao_id,
        'os', r.os_texto,
        'origem_backfill_linha', r.linha_id,
        'origem_backfill', 'planilha_2026'
      )
    )
    RETURNING id INTO v_registro_id;

    v_total_reg := v_total_reg + 1;

    FOR v_ativ IN SELECT atividade_codigo FROM stg_atividades WHERE linha_id = r.linha_id LOOP
      SELECT id INTO v_atividade_id FROM d_atividades WHERE codigo_op = v_ativ.atividade_codigo AND tipo_equipe_id = v_tipo_equipe_id;
      IF v_atividade_id IS NULL THEN
        RAISE WARNING 'Atividade não encontrada: % (linha %)', v_ativ.atividade_codigo, r.linha_id;
        CONTINUE;
      END IF;

      INSERT INTO f_prod_atividades (registro_id, atividade_id, quantidade, preco_upe)
      VALUES (v_registro_id, v_atividade_id, 1, 1);

      v_total_ativ := v_total_ativ + 1;
    END LOOP;
  END LOOP;

  RAISE NOTICE 'OK — % registros criados, % atividades criadas, % linhas já existentes puladas.',
    v_total_reg, v_total_ativ, v_pulados;
END $$;

DROP TABLE stg_registros;
DROP TABLE stg_atividades;
